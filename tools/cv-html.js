// Writes tools/cv-source.html from tools/cv-content.json for printing the PDF,
// in the same template as the CVs sent with applications: a bold centred name,
// centred contact lines, green uppercase section headings over a black rule,
// "Title | Date" heads, grey italic organisation lines and green "Project:" links.
// usage: node tools/cv-html.js
const fs = require("fs");
const path = require("path");
const C = JSON.parse(fs.readFileSync(path.join(__dirname, "cv-content.json"), "utf8"));
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const a = (t, u) => `<a href="${u}">${esc(t)}</a>`;
const bare = (u) => u.replace(/^https?:\/\/(www\.)?/, "").replace(/\/$/, "");

const byUrl = (re) => C.contact.find((c) => c.url && re.test(c.url));
const place = C.contact.find((c) => !c.url);
const email = byUrl(/^mailto:/), site = byUrl(/vercel\.app/), li = byUrl(/linkedin/), gh = byUrl(/github/);
let body = `<h1>${esc(C.name)}</h1>
<p class="contact">${place ? esc(place.text) + " | " : ""}${a(email.text, email.url)}</p>
<p class="contact">Portfolio: ${a(site.text, site.url)} | LinkedIn: ${a(li.text, li.url)} | GitHub: ${a(gh.text, gh.url)}</p>
<h2>Professional Summary</h2>
<p>${esc(C.summary)}</p>
`;
for (const s of C.sections) {
  body += `<h2>${esc(s.title)}</h2>\n`;
  if (s.text) body += `<p>${esc(s.text)}</p>\n`;
  else if (s.skills) body += s.skills.map(([n, d]) => `<p class="skill"><b>${esc(n)}:</b> ${esc(d)}</p>`).join("\n") + "\n";
  else for (const e of s.entries) {
    body += `<div class="entry">\n  <div><span class="title">${esc(e.title)}</span>${e.date ? ` | <span class="date">${esc(e.date)}</span>` : ""}</div>\n`;
    if (e.org) body += `  <div class="sub">${esc(e.org)}</div>\n`;
    if (e.note) body += e.note.split("\n").map((n) => `  <div>${esc(n)}</div>\n`).join("");
    if (e.link) body += `  <div class="link">${esc(e.link.label || "Project")}: ${a(bare(e.link.url), e.link.url)}</div>\n`;
    if (e.bullets) body += `  <ul>\n${e.bullets.map((b) => `    <li>${esc(b)}</li>`).join("\n")}\n  </ul>\n`;
    body += `</div>\n`;
  }
}

const html = `<!doctype html>
<html lang="en-AU">
<head>
<meta charset="utf-8">
<title>${esc(C.name)} - CV</title>
<!-- Generated by tools/cv-html.js from tools/cv-content.json; edit the JSON, not this file. -->
<style>
  @page { size: A4; margin: 11mm 15mm; }
  * { box-sizing: border-box; }
  body { font-family: Calibri, Arial, sans-serif; font-size: 10pt; line-height: 1.25; color: #1a1a1a; margin: 0; }
  h1 { line-height: 1.1; font-size: 22pt; font-weight: 700; text-align: center; margin: 0 0 3pt; color: #111; }
  .contact { text-align: center; margin: 0; font-size: 10pt; }
  a { color: inherit; text-decoration: none; }
  .contact a { color: #1f6e50; }
  h2 { font-size: 12pt; font-weight: 700; text-transform: uppercase; letter-spacing: 0.5pt; color: #1f6e50;
       border-bottom: 1.2pt solid #1a1a1a; margin: 8pt 0 4pt; padding-bottom: 1pt; break-after: avoid; }
  p { margin: 0 0 4pt; }
  .entry { margin: 0 0 5pt; break-inside: avoid; }
  li { break-inside: avoid; margin: 0 0 1pt; }
  .title { font-weight: 700; }
  .date { font-weight: 700; color: #1f6e50; }
  .sub { font-style: italic; color: #555; }
  .link { color: #1f6e50; }
  ul { margin: 2pt 0 0; padding-left: 15pt; }
  .skill { margin: 0 0 2pt; }
</style>
</head>
<body>

${body}
</body>
</html>
`;
fs.writeFileSync(path.join(__dirname, "cv-source.html"), html);
console.log("written tools/cv-source.html");
