// Writes tools/cv-source.html from tools/cv-content.json, in the same
// template as the Word CV (tools/cv-docx.js), for printing the PDF.
// Carlito is metric-compatible with Calibri, so lines break as in Word.
// usage: node tools/cv-html.js
const fs = require("fs");
const path = require("path");
const C = JSON.parse(fs.readFileSync(path.join(__dirname, "cv-content.json"), "utf8"));
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const a = (t, u) => `<a href="${u}">${esc(t)}</a>`;

let body = `<h1>${esc(C.name)}</h1>
<p class="contact">${C.contact.map((c) => (c.url ? a(c.text, c.url) : `<span>${esc(c.text)}</span>`)).join('<i>|</i>')}</p>
<h2>Professional Summary</h2>
<p>${esc(C.summary)}</p>
`;
for (const s of C.sections) {
  body += `<h2>${esc(s.title)}</h2>\n`;
  if (s.text) { body += `<p>${esc(s.text)}</p>\n`; continue; }
  if (s.skills) { body += s.skills.map(([n, d]) => `<p class="skill"><b>${esc(n)} -</b> ${esc(d)}</p>`).join("\n") + "\n"; continue; }
  for (const e of s.entries) {
    const r = e.date ? `<span>${esc(e.date)}</span>` : e.link ? a(e.link.text + " ↗", e.link.url) : "";
    body += `<div class="entry"><p class="title">${esc(e.title)}</p><p class="org"><span>${esc(e.org)}</span>${r}</p>`;
    if (e.note) body += `<p class="note">${esc(e.note)}</p>`;
    if (e.bullets) body += `<ul>${e.bullets.map((b) => `<li>${esc(b)}</li>`).join("")}</ul>`;
    body += `</div>\n`;
  }
}

const html = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>${esc(C.name)} – CV</title>
<!-- Generated by tools/cv-html.js from tools/cv-content.json; edit the JSON, not this file. -->
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Carlito:ital,wght@0,400;0,700;1,400&display=block">
<style>
@page { size: A4; margin: 15.9mm; }
* { box-sizing: border-box; }
html, body { margin: 0; }
body { font-family: Carlito, Calibri, "Liberation Sans", Arial, sans-serif; font-size: 10.5pt; line-height: 1.32; color: #000; }
a { color: #1f4e79; text-decoration: none; }
p { margin: 0; }
h1 { margin: 0 0 1mm; font-size: 18pt; font-weight: 700; }
.contact { font-size: 9pt; color: #404040; margin-bottom: 1mm; }
.contact i { font-style: normal; margin: 0 2.2mm; color: #404040; }
.contact a, .contact span { white-space: nowrap; }
h2 { margin: 4.5mm 0 1.6mm; padding: 1.2mm 0 .5mm; font-size: 10pt; font-weight: 700; text-transform: uppercase;
     border-top: 3px double #808080; border-bottom: 1px solid #808080; break-after: avoid; }
.entry { margin-top: 3mm; break-inside: avoid; }
h2 + .entry { margin-top: .7mm; }
.title { font-weight: 700; }
.org { display: flex; justify-content: space-between; gap: 6mm; color: #404040; }
.org span:last-child, .org a { white-space: nowrap; color: inherit; }
.org a { color: #1f4e79; }
.note { color: #404040; }
ul { margin: .4mm 0 0; padding-left: 9.5mm; }
li { margin: 0 0 .35mm; padding-left: 1mm; }
.skill { margin-bottom: .9mm; }
</style></head><body>
${body}</body></html>
`;
fs.writeFileSync(path.join(__dirname, "cv-source.html"), html);
console.log("written tools/cv-source.html");
