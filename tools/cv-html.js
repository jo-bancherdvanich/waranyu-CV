// Writes tools/cv-source.html from tools/cv-content.json, in the same
// template as the Word CV (tools/cv-docx.js), for printing the PDF:
// a centred EB Garamond name over a green rule, a centred italic contact
// line, green Open Sans section headings with a black rule, bold titles
// with bold dates on the right, green italic organisation lines.
// usage: node tools/cv-html.js
const fs = require("fs");
const path = require("path");
const C = JSON.parse(fs.readFileSync(path.join(__dirname, "cv-content.json"), "utf8"));
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const a = (t, u) => `<a href="${u}">${esc(t)}</a>`;

const contact = C.contact.filter((c) => c.url);   // email, site, LinkedIn, GitHub
let body = `<header>
<h1>${esc(C.name)}</h1>
<p class="contact">${contact.slice(0, 2).map((c) => a(c.text, c.url)).join(" | ")}<br>${contact.slice(2).map((c) => a(c.text, c.url)).join(" | ")}</p>
</header>
<h2 class="center">Professional Summary</h2>
<p class="summary">${esc(C.summary)}</p>
`;
for (const s of C.sections) {
  body += `<section><h2>${esc(s.title)}</h2>\n`;
  if (s.text) body += `<p>${esc(s.text)}</p>\n`;
  else if (s.skills) body += s.skills.map(([n, d]) => `<p class="skill"><b>${esc(n)}</b> – ${esc(d)}</p>`).join("\n") + "\n";
  else for (const e of s.entries) {
    const r = e.date ? `<b class="date">${esc(e.date)}</b>` : e.link ? `<span class="date">${a(e.link.text + " ↗", e.link.url)}</span>` : "";
    body += `<div class="entry"><p class="head"><b>${esc(e.title)}</b>${r}</p><p class="org">${esc(e.org)}</p>`;
    if (e.note) body += e.note.split("\n").map((n) => `<p>${esc(n)}</p>`).join("");
    if (e.bullets) body += `<ul>${e.bullets.map((b) => `<li>${esc(b)}</li>`).join("")}</ul>`;
    body += `</div>\n`;
  }
  body += `</section>\n`;
}

const html = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>${esc(C.name)} – CV</title>
<!-- Generated by tools/cv-html.js from tools/cv-content.json; edit the JSON, not this file. -->
<style>
@font-face { font-family: "EB Garamond"; src: url("fonts/EBGaramond-Regular.ttf"); }
@font-face { font-family: "Open Sans"; src: url("fonts/OpenSans-Regular.ttf"); }
@font-face { font-family: "Open Sans"; src: url("fonts/OpenSans-Bold.ttf"); font-weight: 700; }
@font-face { font-family: "Open Sans"; src: url("fonts/OpenSans-Italic.ttf"); font-style: italic; }
@font-face { font-family: "Open Sans"; src: url("fonts/OpenSans-BoldItalic.ttf"); font-weight: 700; font-style: italic; }
@page { size: A4; margin: 12mm 17mm 12mm 17mm; }
* { box-sizing: border-box; }
html, body { margin: 0; }
body { font-family: "Open Sans", Arial, sans-serif; font-size: 9.5pt; line-height: 1.3; color: #000; }
a { color: inherit; text-decoration: none; }
p { margin: 0; }
header { text-align: center; }
h1 { margin: 0; padding-bottom: 1.6mm; font-family: "EB Garamond", Garamond, Georgia, serif; font-weight: 400; font-size: 32pt; line-height: 1.1;
     border-bottom: 1.5pt solid #278067; }
.contact { margin: 2mm 0 0; font-style: italic; font-size: 11pt; line-height: 1.32; }
.contact a { text-decoration: underline; text-underline-offset: 2px; text-decoration-thickness: .6pt; }
h2 { margin: 3.6mm 0 1.6mm; padding-bottom: .4mm; font-size: 12pt; font-weight: 700; letter-spacing: .03em; text-transform: uppercase; color: #278067;
     border-bottom: 1.5pt solid #000; break-after: avoid; }
h2.center { margin-top: 3mm; text-align: center; color: #000; font-size: 13pt; border: 0; padding: 0; margin-bottom: 1mm; }
.summary { font-style: italic; }
.entry { margin-top: 2.2mm; break-inside: avoid; }
h2 + .entry { margin-top: 0; }
.head { display: flex; justify-content: space-between; gap: 6mm; }
.head .date { white-space: nowrap; }
.head span.date a { color: #278067; font-weight: 400; font-size: 9pt; }
.org { font-style: italic; color: #278067; }
ul { margin: .4mm 0 0; padding-left: 6mm; }
li { margin: 0; padding-left: .8mm; }
.skill { margin-bottom: 1.3mm; }
.skill:last-child { margin-bottom: 0; }
</style></head><body>
${body}</body></html>
`;
fs.writeFileSync(path.join(__dirname, "cv-source.html"), html);
console.log("written tools/cv-source.html");
